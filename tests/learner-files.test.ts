import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { createLearnerFiles, MAX_LEARNER_FILE_BYTES } from '../src/store/learner-files.ts';
import { readTool } from '../src/agent/tools/read.ts';
import { pdfInfo } from '../src/agent/subagents/pdf-ops.ts';

test('uploaded learner files preserve original bytes and names across reload and remain isolated', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'lh-files-test-'));
  t.after(() => fs.rm(directory, { recursive: true, force: true }));
  const alice = createLearnerFiles(path.join(directory, 'alice'));
  const bob = createLearnerFiles(path.join(directory, 'bob'));
  assert.deepEqual(await alice.list(), []);
  const bytes = new Uint8Array(await fs.readFile(new URL('./fixtures/sample-3page.pdf', import.meta.url)));
  const uploaded = await alice.put('Mes notes λ.pdf', bytes);
  const repeated = await alice.put('Mes notes λ.pdf', bytes);
  assert.notEqual(uploaded.id, repeated.id, 'repeated names never overwrite a previous upload');
  const reopened = createLearnerFiles(path.join(directory, 'alice'));
  assert.equal((await reopened.list()).length, 2);
  const file = await reopened.read(uploaded.id);
  assert(file); assert.equal(file.name, 'Mes notes λ.pdf');
  assert.deepEqual(new Uint8Array(file.bytes), bytes);
  assert.deepEqual(new Uint8Array(await fs.readFile(uploaded.path)), bytes, 'the native agent can read the exact path displayed to the learner');
  assert.equal((await fs.stat(uploaded.path)).mode & 0o777, 0o600);
  assert.equal((await pdfInfo(uploaded.path)).page_count, 3, 'the production PDF reader consumes the uploaded path');
  const note = await alice.put('reasoning.txt', new TextEncoder().encode('My reasoning is preserved exactly.'));
  const read = await readTool.execute!('uploaded-notes', { path: note.path });
  assert.equal(read.details, 'My reasoning is preserved exactly.', 'the production agent read tool consumes uploaded notes');
  await alice.remove(note.id);
  assert.equal(await bob.read(uploaded.id), null);
  assert.equal(await bob.remove(uploaded.id), false);
  assert.equal(await reopened.remove(uploaded.id), true);
  assert.equal(await reopened.read(uploaded.id), null);
  assert.equal((await reopened.list()).length, 1);
});

test('learner file adapter rejects traversal, oversized files and symlinks', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'lh-files-test-'));
  t.after(() => fs.rm(directory, { recursive: true, force: true }));
  const files = createLearnerFiles(directory);
  for (const name of ['../outside.txt', 'folder/file', 'folder\\file', 'bad\x00name', '', 'a'.repeat(181)]) await assert.rejects(files.put(name, new Uint8Array([1])));
  await assert.rejects(files.put('too-large', new Uint8Array(MAX_LEARNER_FILE_BYTES + 1)), /8 MiB/);
  const file = await files.put('safe.txt', new Uint8Array([42]));
  await fs.unlink(file.path);
  await fs.symlink('/etc/passwd', file.path);
  assert.equal(await files.read(file.id), null);
  assert.equal(await files.remove(file.id), false);
  assert.deepEqual(await files.list(), []);
  for (const id of ['../outside', '/etc/passwd', 'not-an-id']) assert.equal(await files.read(id), null);
});

test('multipart HTTP service persists, lists, downloads and deletes private file bytes', async t => {
  const { stores } = await import('../src/server/stores.ts');
  const service = await import('../src/server/learner-files.ts');
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'lh-files-http-test-'));
  const original = stores.learnerFiles;
  stores.learnerFiles = createLearnerFiles(directory);
  t.after(async () => { stores.learnerFiles = original; await fs.rm(directory, { recursive: true, force: true }); });
  const body = new FormData();
  const source = new Uint8Array([0, 255, 42, 128, 10]);
  body.append('files', new File([source], "λ notes' (1).bin"));
  const uploaded = await service.uploadLearnerFiles(new Request('https://learn.test/api/files', { method: 'POST', body }));
  assert.equal(uploaded.status, 200);
  const data = await uploaded.json(); const id = data.uploaded[0].id;
  const listing = await (await service.learnerFilesResponse()).json();
  assert.equal(listing.files[0].id, id);
  const download = await service.downloadLearnerFile(id);
  assert.equal(download.headers.get('content-type'), 'application/octet-stream');
  assert.match(download.headers.get('content-disposition')!, /%CE%BB.*%27.*%28/);
  assert.deepEqual(new Uint8Array(await download.arrayBuffer()), source);
  assert.equal((await service.deleteLearnerFile(id)).status, 200);
  assert.equal((await service.downloadLearnerFile(id)).status, 404);
  assert.deepEqual((await (await service.learnerFilesResponse()).json()).files, []);
  const oversized = new Request('https://learn.test/api/files', { method: 'POST', body: new Uint8Array(16 * 1024 * 1024 + 1) });
  assert.equal((await service.uploadLearnerFiles(oversized)).status, 413);
  const malformed = new Request('https://learn.test/api/files', { method: 'POST', body: 'not multipart' });
  assert.equal((await service.uploadLearnerFiles(malformed)).status, 400);
});
